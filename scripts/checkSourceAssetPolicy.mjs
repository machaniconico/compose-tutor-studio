import { readdir } from 'node:fs/promises';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultRepoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const ignoredDirs = new Set([
  '.git',
  '.omc',
  '.next',
  '.pnpm-store',
  '.turbo',
  '.vite',
  'build',
  'coverage',
  'dist',
  'node_modules',
  'playwright-report',
  'target',
  'test-results',
]);

const controlledAssetExtensions = new Set([
  '.avi',
  '.flac',
  '.gif',
  '.icns',
  '.ico',
  '.jpg',
  '.jpeg',
  '.mid',
  '.midi',
  '.mov',
  '.mp3',
  '.mp4',
  '.ogg',
  '.p12',
  '.pfx',
  '.png',
  '.wav',
  '.webp',
  '.zip',
]);

// Tauri icon set generated by `pnpm --dir apps/desktop icon` from the original app-icon.svg.
const allowedIconDirectory = 'apps/desktop/src-tauri/icons/';
const allowedIconExtensions = new Set(['.png', '.ico', '.icns', '.svg']);

async function listFiles(root) {
  const entries = await readdir(root, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = join(root, entry.name);
    if (entry.isDirectory()) {
      if (ignoredDirs.has(entry.name)) continue;
      files.push(...(await listFiles(path)));
    } else if (entry.isFile()) {
      files.push(path);
    }
  }

  return files;
}

export async function checkSourceAssetPolicy(repoRoot = defaultRepoRoot) {
  const files = await listFiles(repoRoot);
  const issues = [];

  for (const file of files) {
    const extension = extname(file).toLowerCase();
    if (!controlledAssetExtensions.has(extension)) continue;

    const relativePath = relative(repoRoot, file).replaceAll('\\', '/');
    if (relativePath.startsWith(allowedIconDirectory) && allowedIconExtensions.has(extension)) continue;

    issues.push(relativePath);
  }

  return issues;
}

async function main() {
  const issues = await checkSourceAssetPolicy();

  if (issues.length > 0) {
    console.error(`Source asset policy check failed: ${issues.length} unexpected asset file(s).`);
    for (const issue of issues) {
      console.error(`FAIL ${issue}`);
    }
    console.error('Add only original/owned assets, then explicitly whitelist required app assets.');
    process.exitCode = 1;
    return;
  }

  console.log('Source asset policy check passed: no unexpected image, audio, video, archive, or signing asset files detected.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
